// 2. Model — holds state (nothing for now)
type model struct{}

// 3. Init — runs once at start (nothing for now)
func (m model) Init() tea.Cmd {
    return nil
}

// 4. Update — handle keypresses
func (m model) Update(msg tea.Msg) (tea.Model, tea.Cmd) {
    switch msg := msg.(type) {
    case tea.KeyMsg:
        if msg.String() == "q" {
            return m, tea.Quit
        }
    }
    return m, nil
}

// 5. View — this is where your layout lives
func (m model) View() string {

    // Left block style
    leftStyle := lipgloss.NewStyle().
        Width(70).
        Padding(1, 2)

    // Right block style
    rightStyle := lipgloss.NewStyle().
        Width(50).
        Padding(1, 2)

    // Render each block
    left := leftStyle.Render(asciiArt)
    right := rightStyle.Render("Lorem")

    // Join them side by side — like flexbox row
    return lipgloss.JoinHorizontal(lipgloss.Top, left, right)
}

// 6. Bubbletea handler for Wish
func teaHandler(s ssh.Session) (tea.Model, []tea.ProgramOption) {
    return model{}, []tea.ProgramOption{tea.WithAltScreen()}
}

func main() {
    s, err := wish.NewServer(
        wish.WithAddress("localhost:2222"),
        wish.WithHostKeyPath(".ssh/id_ed25519"),
        wish.WithMiddleware(
            bm.Middleware(teaHandler),
        ),
    )
    if err != nil {
        fmt.Println("Error starting server:", err)
        os.Exit(1)
    }

    // Start server and wait for Ctrl+C to stop
    done := make(chan os.Signal, 1)
    signal.Notify(done, os.Interrupt, syscall.SIGINT, syscall.SIGTERM)

    go func() {
        if err := s.ListenAndServe(); err != nil {
            fmt.Println("Server stopped:", err)
        }
    }()

    fmt.Println("SSH server running on localhost:2222")
    fmt.Println("Connect with: ssh localhost -p 2222")
    <-done

    ctx, cancel := context.WithTimeout(context.Background(), 5*time.Second)
    defer cancel()
    s.Shutdown(ctx)
}